CREATE OR REPLACE FUNCTION public.handle_new_auth_user()
RETURNS TRIGGER
LANGUAGE PLPGSQL
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  invitation public.account_invitations%ROWTYPE;
BEGIN
  SELECT *
  INTO invitation
  FROM public.account_invitations
  WHERE LOWER(email) = LOWER(NEW.email)
    AND status = 'pending'
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'This account has not been invited';
  END IF;

  IF invitation.role = 'student'
     AND COALESCE(NEW.raw_user_meta_data ->> 'student_id', '') <> invitation.student_id THEN
    RAISE EXCEPTION 'Student ID does not match the invitation';
  END IF;

  INSERT INTO public.users (id, role, full_name, student_id, email)
  VALUES (
    NEW.id,
    invitation.role,
    NULLIF(BTRIM(NEW.raw_user_meta_data ->> 'full_name'), ''),
    invitation.student_id,
    LOWER(NEW.email)
  );

  UPDATE public.account_invitations
  SET status = 'accepted', accepted_by = NEW.id, accepted_at = NOW()
  WHERE id = invitation.id;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.handle_new_auth_user();

CREATE OR REPLACE FUNCTION public.handle_zone_status()
RETURNS TRIGGER
LANGUAGE PLPGSQL
SET search_path = ''
AS $$
BEGIN
  NEW.status := CASE
    WHEN NOT NEW.is_active THEN 'Inactive'
    WHEN NEW.current_occupancy >= NEW.capacity THEN 'Full'
    WHEN NEW.current_occupancy::NUMERIC / NEW.capacity >= 0.9 THEN 'Nearly Full'
    ELSE 'Available'
  END;
  NEW.updated_at := NOW();
  RETURN NEW;
END;
$$;

