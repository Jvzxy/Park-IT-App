CREATE OR REPLACE FUNCTION public.update_report_status(
  p_report_id BIGINT,
  p_status TEXT,
  p_remark TEXT DEFAULT ''
)
RETURNS VOID
LANGUAGE PLPGSQL
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  report_row public.parking_reports%ROWTYPE;
BEGIN
  IF p_status IS NULL OR p_status NOT IN ('Pending', 'In Progress', 'Resolved', 'Rejected') THEN
    RAISE EXCEPTION 'Invalid report status';
  END IF;

  SELECT * INTO report_row
  FROM public.parking_reports
  WHERE id = p_report_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Report not found';
  END IF;

  IF public.current_app_role() <> 'admin'
     AND NOT (public.current_app_role() = 'guard' AND public.is_zone_guard(report_row.zone_id)) THEN
    RAISE EXCEPTION 'You are not assigned to this report';
  END IF;

  UPDATE public.parking_reports
  SET status = p_status,
      assigned_guard_id = CASE WHEN public.current_app_role() = 'guard' THEN auth.uid() ELSE assigned_guard_id END,
      resolved_at = CASE WHEN p_status = 'Resolved' THEN NOW() ELSE NULL END
  WHERE id = p_report_id;

  IF NULLIF(BTRIM(p_remark), '') IS NOT NULL THEN
    INSERT INTO public.report_updates (report_id, remark, guard_id)
    VALUES (p_report_id, BTRIM(p_remark), auth.uid());
  END IF;

  INSERT INTO public.notifications (user_id, message)
  VALUES (report_row.student_id, 'Your parking report #' || p_report_id || ' is now ' || LOWER(p_status) || '.');

  INSERT INTO public.activity_logs (user_id, action, details)
  VALUES (auth.uid(), 'report_status_changed', JSONB_BUILD_OBJECT('report_id', p_report_id, 'status', p_status));
END;
$$;

CREATE OR REPLACE FUNCTION public.review_report(
  p_report_id BIGINT,
  p_action TEXT,
  p_remark TEXT DEFAULT '',
  p_duplicate_of BIGINT DEFAULT NULL
)
RETURNS VOID
LANGUAGE PLPGSQL
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  report_row public.parking_reports%ROWTYPE;
  new_status TEXT;
BEGIN
  IF public.current_app_role() <> 'admin' THEN
    RAISE EXCEPTION 'Administrator access required';
  END IF;

  SELECT * INTO report_row FROM public.parking_reports WHERE id = p_report_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Report not found';
  END IF;

  IF p_action = 'reopen' THEN
    new_status := 'Pending';
    UPDATE public.parking_reports SET status = new_status, resolved_at = NULL, is_duplicate = FALSE, duplicate_of = NULL WHERE id = p_report_id;
  ELSIF p_action = 'duplicate' THEN
    IF p_duplicate_of IS NULL OR p_duplicate_of = p_report_id THEN
      RAISE EXCEPTION 'Choose another report to mark as the duplicate';
    END IF;
    new_status := 'Rejected';
    UPDATE public.parking_reports SET status = new_status, is_duplicate = TRUE, duplicate_of = p_duplicate_of WHERE id = p_report_id;
  ELSIF p_action = 'spam' THEN
    new_status := 'Rejected';
    UPDATE public.parking_reports SET status = new_status WHERE id = p_report_id;
  ELSE
    RAISE EXCEPTION 'Invalid review action';
  END IF;

  INSERT INTO public.report_updates (report_id, remark, guard_id)
  VALUES (p_report_id, COALESCE(NULLIF(BTRIM(p_remark), ''), 'Administrator marked this report as ' || p_action || '.'), auth.uid());
  INSERT INTO public.activity_logs (user_id, action, details)
  VALUES (auth.uid(), 'report_reviewed', JSONB_BUILD_OBJECT('report_id', p_report_id, 'action', p_action));
  INSERT INTO public.notifications (user_id, message)
  VALUES (report_row.student_id, 'Your parking report #' || p_report_id || ' has been reviewed.');
END;
$$;

CREATE OR REPLACE FUNCTION public.set_zone_occupancy(p_zone_id BIGINT, p_occupancy INTEGER)
RETURNS VOID
LANGUAGE PLPGSQL
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  old_status TEXT;
  zone_row public.parking_zones%ROWTYPE;
BEGIN
  SELECT * INTO zone_row FROM public.parking_zones WHERE id = p_zone_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Parking zone not found';
  END IF;

  IF public.current_app_role() <> 'admin'
     AND NOT (public.current_app_role() = 'guard' AND public.is_zone_guard(p_zone_id)) THEN
    RAISE EXCEPTION 'You are not assigned to this zone';
  END IF;
  IF p_occupancy IS NULL OR p_occupancy < 0 OR p_occupancy > zone_row.capacity THEN
    RAISE EXCEPTION 'Occupancy must be between zero and the zone capacity';
  END IF;

  old_status := zone_row.status;
  UPDATE public.parking_zones SET current_occupancy = p_occupancy WHERE id = p_zone_id RETURNING * INTO zone_row;

  IF old_status IS DISTINCT FROM zone_row.status THEN
    INSERT INTO public.notifications (user_id, message)
    SELECT id, zone_row.name || ' is now ' || LOWER(zone_row.status) || '.'
    FROM public.users
    WHERE role = 'student' AND is_active;
  END IF;

END;
$$;

CREATE OR REPLACE FUNCTION public.publish_announcement(
  p_message TEXT,
  p_audience TEXT DEFAULT 'student',
  p_expires_at TIMESTAMPTZ DEFAULT NULL
)
RETURNS BIGINT
LANGUAGE PLPGSQL
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  announcement_id BIGINT;
BEGIN
  IF public.current_app_role() NOT IN ('admin', 'guard') THEN
    RAISE EXCEPTION 'Staff access required';
  END IF;
  IF NULLIF(BTRIM(p_message), '') IS NULL OR p_audience IS NULL OR p_audience NOT IN ('student', 'guard', 'all') THEN
    RAISE EXCEPTION 'A message and valid audience are required';
  END IF;
  IF p_expires_at IS NOT NULL AND p_expires_at <= NOW() THEN
    RAISE EXCEPTION 'Announcement expiration must be in the future';
  END IF;

  INSERT INTO public.announcements (message, audience, expires_at, created_by)
  VALUES (BTRIM(p_message), p_audience, p_expires_at, auth.uid())
  RETURNING id INTO announcement_id;

  INSERT INTO public.notifications (user_id, message)
  SELECT id, BTRIM(p_message)
  FROM public.users
  WHERE is_active
    AND (p_audience = 'all' OR role = p_audience);

  RETURN announcement_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_update_user(
  p_user_id UUID,
  p_role TEXT,
  p_is_active BOOLEAN
)
RETURNS VOID
LANGUAGE PLPGSQL
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF public.current_app_role() <> 'admin' THEN
    RAISE EXCEPTION 'Administrator access required';
  END IF;
  IF p_role IS NULL OR p_role NOT IN ('student', 'guard', 'admin') OR p_is_active IS NULL THEN
    RAISE EXCEPTION 'Invalid account role';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.users
    WHERE id = p_user_id AND role = 'admin' AND is_active
      AND (p_role <> 'admin' OR NOT p_is_active)
  ) AND NOT EXISTS (
    SELECT 1 FROM public.users
    WHERE role = 'admin' AND is_active AND id <> p_user_id
  ) THEN
    RAISE EXCEPTION 'At least one active administrator must remain';
  END IF;

  UPDATE public.users SET role = p_role, is_active = p_is_active WHERE id = p_user_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Account not found'; END IF;

  INSERT INTO public.activity_logs (user_id, action, details)
  VALUES (auth.uid(), 'account_updated', JSONB_BUILD_OBJECT('target_user_id', p_user_id, 'role', p_role, 'is_active', p_is_active));
END;
$$;

CREATE OR REPLACE FUNCTION public.create_account_invitation(
  p_email TEXT,
  p_role TEXT,
  p_student_id TEXT DEFAULT NULL
)
RETURNS UUID
LANGUAGE PLPGSQL
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  invitation_id UUID;
BEGIN
  IF public.current_app_role() <> 'admin' THEN
    RAISE EXCEPTION 'Administrator access required';
  END IF;
  IF p_role IS NULL OR p_role NOT IN ('student', 'guard', 'admin') OR NULLIF(BTRIM(p_email), '') IS NULL THEN
    RAISE EXCEPTION 'A valid role and email are required';
  END IF;
  IF BTRIM(p_email) !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' THEN
    RAISE EXCEPTION 'A valid email address is required';
  END IF;
  IF (p_role = 'student' AND NULLIF(BTRIM(p_student_id), '') IS NULL)
     OR (p_role <> 'student' AND p_student_id IS NOT NULL) THEN
    RAISE EXCEPTION 'A student ID is required only for student invitations';
  END IF;
  IF p_role = 'student' AND BTRIM(p_student_id) !~ '^[0-9]{6,20}$' THEN
    RAISE EXCEPTION 'Student ID must contain 6 to 20 digits';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM public.users AS existing_user
    WHERE LOWER(existing_user.email) = LOWER(BTRIM(p_email))
       OR (p_student_id IS NOT NULL AND existing_user.student_id = BTRIM(p_student_id))
  ) THEN
    RAISE EXCEPTION 'An account already exists for this email or Student ID';
  END IF;

  INSERT INTO public.account_invitations (email, role, student_id, invited_by)
  VALUES (LOWER(BTRIM(p_email)), p_role, NULLIF(BTRIM(p_student_id), ''), auth.uid())
  RETURNING id INTO invitation_id;

  INSERT INTO public.activity_logs (user_id, action, details)
  VALUES (auth.uid(), 'account_invited', JSONB_BUILD_OBJECT('email', LOWER(BTRIM(p_email)), 'role', p_role));
  RETURN invitation_id;
END;
$$;

